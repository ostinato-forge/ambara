"""Generate weekly hygiene PR body for the knowledge repo."""

from __future__ import annotations

from datetime import datetime

from ambara.core.context_rendering import (
    safe_artifact_ref,
    sanitize_source_paths,
    sanitize_untrusted_source_text,
)
from ambara.core.curation import CurationAdvisory
from ambara.core.hygiene import HygieneItem
from ambara.core.schema import Entry


def build_hygiene_pr_body(
    *,
    stale_entries: list[Entry],
    expired_active_entries: list[HygieneItem] | None = None,
    revalidation_entries: list[HygieneItem],
    contradictions: list[tuple[str, list[str]]],
    now: datetime,
    curation_advisories: list[CurationAdvisory] | None = None,
) -> str:
    expired_active_entries = expired_active_entries or []
    curation_advisories = curation_advisories or []
    sections: list[str] = []
    sections.append(f"## Weekly Knowledge Hygiene — {now.strftime('%Y-%m-%d')}\n")

    if (
        not stale_entries
        and not expired_active_entries
        and not revalidation_entries
        and not contradictions
        and not curation_advisories
    ):
        sections.append("Knowledge repo is clean. No issues found.\n")
        return "\n".join(sections)

    if expired_active_entries:
        sections.append(f"### Expired Active Context ({len(expired_active_entries)})\n")
        sections.append(
            "These active entries are past `expires_at` and will be marked expired in "
            "this review branch:\n"
        )
        for item in expired_active_entries:
            expires_at = item.expires_at.strftime("%Y-%m-%d") if item.expires_at else "unknown"
            sections.append(f"- **{item.id}**: {item.title} (expires_at: {expires_at})")
        sections.append("")

    if stale_entries:
        sections.append(f"### Stale Entries ({len(stale_entries)})\n")
        sections.append("These entries have not been updated in 90+ days:\n")
        for entry in stale_entries:
            age = (now - entry.frontmatter.updated_at).days
            sections.append(
                f"- **{entry.frontmatter.id}**: {entry.frontmatter.title} "
                f"({age} days since last update)"
            )
        sections.append("")

    if revalidation_entries:
        sections.append(f"### Revalidation Due ({len(revalidation_entries)})\n")
        sections.append(
            "These durable entries have explicit `review_after` dates on or before this run date:\n"
        )
        for item in revalidation_entries:
            review_after = (
                item.review_after.strftime("%Y-%m-%d") if item.review_after else "unknown"
            )
            sections.append(f"- **{item.id}**: {item.title} (review_after: {review_after})")
        sections.append("")

    if contradictions:
        sections.append(f"### Possible Contradictions ({len(contradictions)})\n")
        for new_id, conflict_ids in contradictions:
            sections.append(f"- **{new_id}** may conflict with: {', '.join(conflict_ids)}")
        sections.append("")

    if curation_advisories:
        sections.append(f"### Completed Artifact Revalidation ({len(curation_advisories)})\n")
        sections.append(
            "These durable entries match recently completed labeled artifacts and should be "
            "checked before agents keep treating them as current:\n"
        )
        for advisory in curation_advisories:
            paths = ", ".join(sanitize_source_paths(advisory.changed_paths, max_paths=3))
            paths = paths or "metadata-only"
            matched = ", ".join(advisory.matched_terms)
            artifact_title = _markdown_inline(
                sanitize_untrusted_source_text(
                    advisory.artifact_title,
                    field="title",
                    max_chars=120,
                )
                or "untitled artifact"
            )
            artifact_ref = safe_artifact_ref(advisory.artifact_ref)
            artifact = (
                f"[{artifact_title}]({artifact_ref})"
                if artifact_ref is not None
                else artifact_title
            )
            sections.append(
                f"- **{advisory.entry_id}**: {advisory.entry_title} - "
                f"revalidate after {artifact} "
                f"({advisory.source_input_source}; matched: {matched}; paths: {paths})"
            )
        sections.append("")

    sections.append(
        "---\n*Auto-generated by `ambara`. Review and resolve, or close to acknowledge.*"
    )
    return "\n".join(sections)


def _markdown_inline(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace("[", "\\[")
        .replace("]", "\\]")
        .replace("(", "\\(")
        .replace(")", "\\)")
    )
