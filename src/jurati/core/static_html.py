"""Generate a static HTML browser for Jurati knowledge repos."""

from __future__ import annotations

import html
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING

import frontmatter

from jurati.core.graph import EntryGraph, build_entry_graph
from jurati.core.index import Index, parse_entry
from jurati.core.paths import TYPE_DIRS
from jurati.core.schema import Entry, Sensitivity

if TYPE_CHECKING:
    from collections.abc import Iterable


_WIKI_LINK_RE = re.compile(r"(?<!!)\[\[([^\]\n]+)\]\]")
_MARKER = ".jurati-static-site"


@dataclass(frozen=True)
class StaticHtmlResult:
    output_dir: Path
    pages: tuple[Path, ...]
    skipped_restricted: int
    errors: tuple[str, ...] = ()


def generate_static_html(
    knowledge_repo: Path, *, output_dir: Path | None = None
) -> StaticHtmlResult:
    root = knowledge_repo.resolve()
    site_dir = output_dir.resolve() if output_dir is not None else root / "_site"
    index, errors = _load_index(root)
    graph = build_entry_graph(index)
    visible_entries = _visible_entries(index.entries.values())
    visible_ids = {entry.frontmatter.id for entry in visible_entries}
    restricted_ids = set(graph.restricted_entry_ids)

    _prepare_site_dir(site_dir, root)
    (site_dir / "entries").mkdir(parents=True, exist_ok=True)
    (site_dir / _MARKER).write_text("generated by jurati html\n", encoding="utf-8")

    pages: list[Path] = []
    index_path = site_dir / "index.html"
    index_path.write_text(_render_index(visible_entries), encoding="utf-8")
    pages.append(index_path)

    for entry in visible_entries:
        page = site_dir / "entries" / f"{entry.frontmatter.id}.html"
        page.write_text(
            _render_entry_page(entry, graph, visible_ids, restricted_ids),
            encoding="utf-8",
        )
        pages.append(page)

    return StaticHtmlResult(
        output_dir=site_dir,
        pages=tuple(pages),
        skipped_restricted=len(index.entries) - len(visible_entries),
        errors=tuple(errors),
    )


def _prepare_site_dir(site_dir: Path, root: Path) -> None:
    if site_dir == root:
        raise ValueError("static HTML output directory must not be the knowledge repo root")

    marker = site_dir / _MARKER
    if marker.exists():
        shutil.rmtree(site_dir)
        return

    if site_dir.exists() and any(site_dir.iterdir()):
        raise ValueError(
            "static HTML output directory already exists and is not marked "
            f"as generated: {site_dir}"
        )


def _load_index(root: Path) -> tuple[Index, list[str]]:
    index = Index()
    errors: list[str] = []
    for directory in TYPE_DIRS.values():
        entry_dir = root / directory
        if not entry_dir.exists():
            continue
        for path in sorted(entry_dir.glob("*.md")):
            relative_path = path.relative_to(root).as_posix()
            try:
                post = frontmatter.load(path)
                index.add(parse_entry(relative_path, dict(post.metadata), post.content))
            except Exception as exc:
                errors.append(f"{relative_path}: parse error: {exc}")
    return index, errors


def _visible_entries(entries: Iterable[Entry]) -> list[Entry]:
    return sorted(
        (entry for entry in entries if entry.frontmatter.sensitivity != Sensitivity.RESTRICTED),
        key=lambda entry: (
            str(entry.frontmatter.type),
            entry.frontmatter.updated_at.isoformat(),
            entry.frontmatter.id,
        ),
    )


def _render_index(entries: list[Entry]) -> str:
    rows = "\n".join(_index_row(entry) for entry in entries)
    body = f"""
<main>
  <h1>Jurati Context Browser</h1>
  <p class="lede">Generated from the local Jurati knowledge repo.</p>
  <table>
    <thead>
      <tr>
        <th>Title</th>
        <th>Type</th>
        <th>Status</th>
        <th>Projects</th>
        <th>Updated</th>
      </tr>
    </thead>
    <tbody>
{rows}
    </tbody>
  </table>
</main>
"""
    return _page("Jurati Context Browser", body)


def _index_row(entry: Entry) -> str:
    fm = entry.frontmatter
    return (
        "      <tr>"
        f'<td><a href="entries/{_attr(fm.id)}.html">{_text(fm.title)}</a></td>'
        f"<td>{_text(str(fm.type))}</td>"
        f"<td>{_text(str(fm.status))}</td>"
        f"<td>{_text(', '.join(fm.projects))}</td>"
        f"<td>{_text(fm.updated_at.isoformat())}</td>"
        "</tr>"
    )


def _render_entry_page(
    entry: Entry,
    graph: EntryGraph,
    visible_ids: set[str],
    restricted_ids: set[str],
) -> str:
    fm = entry.frontmatter
    links = graph.links_for(fm.id)
    outgoing = [entry_id for entry_id in links["outgoing"] if entry_id in visible_ids]
    backlinks = [
        entry_id
        for entry_id in links["backlinks"]
        if entry_id in visible_ids and entry_id not in graph.restricted_entry_ids
    ]
    broken = [item for item in links["broken"] if item["target"] not in visible_ids]

    body = f"""
<main>
  <p><a href="../index.html">Back to index</a></p>
  <h1>{_text(fm.title)}</h1>
  <dl class="meta">
    <dt>ID</dt><dd>{_text(fm.id)}</dd>
    <dt>Type</dt><dd>{_text(str(fm.type))}</dd>
    <dt>Status</dt><dd>{_text(str(fm.status))}</dd>
    <dt>Projects</dt><dd>{_text(", ".join(fm.projects))}</dd>
    <dt>Updated</dt><dd>{_text(fm.updated_at.isoformat())}</dd>
  </dl>
  <section class="entry-body">
{_render_body(entry.body, visible_ids, restricted_ids, link_prefix="")}
  </section>
  <section>
    <h2>Links</h2>
    {_link_list(outgoing, empty="No outgoing links.")}
  </section>
  <section>
    <h2>Backlinks</h2>
    {_link_list(backlinks, empty="No backlinks.")}
  </section>
  <section>
    <h2>Broken Links</h2>
    {_broken_list(broken)}
  </section>
</main>
"""
    return _page(f"{fm.title} - Jurati", body)


def _render_body(
    body: str,
    visible_ids: set[str],
    restricted_ids: set[str],
    *,
    link_prefix: str,
) -> str:
    lines: list[str] = []
    for raw_line in body.splitlines():
        line = raw_line.strip()
        if not line:
            continue
        if line.startswith("## "):
            lines.append(
                f"    <h3>{_render_inline(line[3:], visible_ids, restricted_ids, link_prefix)}</h3>"
            )
        elif line.startswith("# "):
            lines.append(
                f"    <h2>{_render_inline(line[2:], visible_ids, restricted_ids, link_prefix)}</h2>"
            )
        elif line.startswith("- "):
            rendered = _render_inline(line[2:], visible_ids, restricted_ids, link_prefix)
            lines.append(f"    <p>&bull; {rendered}</p>")
        else:
            lines.append(
                f"    <p>{_render_inline(line, visible_ids, restricted_ids, link_prefix)}</p>"
            )
    return "\n".join(lines)


def _render_inline(
    value: str,
    visible_ids: set[str],
    restricted_ids: set[str],
    link_prefix: str,
) -> str:
    parts: list[str] = []
    cursor = 0
    for match in _WIKI_LINK_RE.finditer(value):
        parts.append(_text(value[cursor : match.start()]))
        inner = match.group(1).strip()
        target_part, _, label_part = inner.partition("|")
        target = target_part.split("#", 1)[0].strip()
        label = label_part.strip() or target
        if target in visible_ids:
            parts.append(f'<a href="{_attr(link_prefix)}{_attr(target)}.html">{_text(label)}</a>')
        elif target in restricted_ids:
            parts.append('<span class="restricted-link">restricted link omitted</span>')
        else:
            parts.append(f'<span class="broken">{_text(match.group(0))}</span>')
        cursor = match.end()
    parts.append(_text(value[cursor:]))
    return "".join(parts)


def _link_list(ids: list[str], *, empty: str) -> str:
    if not ids:
        return f"<p>{_text(empty)}</p>"
    items = "\n".join(
        f'      <li><a href="{_attr(entry_id)}.html">{_text(entry_id)}</a></li>' for entry_id in ids
    )
    return f"<ul>\n{items}\n    </ul>"


def _broken_list(items: list[dict[str, str]]) -> str:
    if not items:
        return "<p>No broken links.</p>"
    rendered = "\n".join(
        f'      <li><span class="broken">{_text(item["raw"])}</span></li>' for item in items
    )
    return f"<ul>\n{rendered}\n    </ul>"


def _page(title: str, body: str) -> str:
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{_text(title)}</title>
  <style>{_style()}</style>
</head>
<body>
{body.strip()}
</body>
</html>
"""


def _style() -> str:
    return """
body { font-family: system-ui, sans-serif; margin: 0; color: #17202a; background: #f6f8fb; }
main { max-width: 1040px; margin: 0 auto; padding: 32px 20px 56px; }
a { color: #0b63ce; }
table { width: 100%; border-collapse: collapse; background: white; }
th, td { padding: 10px 12px; border-bottom: 1px solid #d8dee8; text-align: left; }
th { font-size: 0.82rem; text-transform: uppercase; letter-spacing: 0; color: #536071; }
.lede { color: #536071; }
.meta { display: grid; grid-template-columns: max-content 1fr; gap: 8px 14px; }
.meta dt { font-weight: 700; color: #536071; }
.meta dd { margin: 0; }
.entry-body { background: white; border: 1px solid #d8dee8; padding: 18px 20px; }
.broken { color: #a33a00; font-weight: 700; }
"""


def _text(value: str) -> str:
    return html.escape(value, quote=False)


def _attr(value: str) -> str:
    return html.escape(value, quote=True)
